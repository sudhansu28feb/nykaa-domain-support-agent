"""
Deterministic Nykaa Order Dataset Generator and Task 1 Deliverable.

Treat docs/IITR_Final_Capstone_Brief.pdf as authoritative source of truth.
Produces an ORDERS list of >=40 order records (50 generated by default).

Required Fields:
- record_id: str
- category: str (Apparel, Electronics, Home, Footwear, Beauty; >=3 records each)
- status: str (Placed, Shipped, Delivered, Returned, Refunded; >=1 record each)
- order_value_inr: int (Realistic price range with 1-sentence reasoning)
- days_since_created: int (0 to 30)
- delayed_shipment: bool (10% to 30% rate)
"""

import sys
from typing import List

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

from nykaa_support.dataset import (
    DEFAULT_ORDER_COUNT,
    DEFAULT_SEED,
    REQUIRED_CATEGORIES,
    REQUIRED_STATUSES,
    OrderRecord,
    check_order_status,
    export_orders_to_json,
    generate_orders,
    get_dataset_summary,
    get_order_by_id,
)

# Realistic Price Range Justification (Task 1):
PRICE_RANGE_REASONING = (
    "Order values are chosen in the ₹445 to ₹4,899 range reflecting typical Indian retail basket sizes "
    "for beauty cosmetics, personal care, apparel, and styling appliances on Nykaa."
)

# Canonical module-level ORDERS list generated deterministically
ORDERS: List[OrderRecord] = generate_orders(seed=DEFAULT_SEED, count=DEFAULT_ORDER_COUNT)


def print_validation_report() -> None:
    """Print the required Task 1 validation report to stdout."""
    summary = get_dataset_summary(ORDERS)

    print("=" * 70)
    print("NYKAA DOMAIN SUPPORT AGENT: DATASET VALIDATION REPORT (TASK 1)")
    print("=" * 70)
    print(f"Total Orders Generated: {summary.total_orders} (Requirement: >= 40)")
    print(f"Random Seed: {DEFAULT_SEED} (Deterministic & Reproducible)")
    print(f"Price Range Reasoning: {PRICE_RANGE_REASONING}\n")

    print("--- 1. Category Distribution (Requirement: >= 3 records each) ---")
    for cat in REQUIRED_CATEGORIES:
        count = summary.categories.get(cat, 0)
        status_flag = "PASS" if count >= 3 else "FAIL"
        print(f"  [{status_flag}] {cat:<15}: {count:>2} records (>= 3 required)")

    print("\n--- 2. Status Distribution (Requirement: >= 1 record each) ---")
    for st in REQUIRED_STATUSES:
        count = summary.statuses.get(st, 0)
        status_flag = "PASS" if count >= 1 else "FAIL"
        print(f"  [{status_flag}] {st:<15}: {count:>2} records (>= 1 required)")

    print("\n--- 3. Delayed Shipment Rate (Requirement: 10% to 30%) ---")
    delayed_pct = summary.delayed_percentage
    delayed_pass = 10.0 <= delayed_pct <= 30.0
    status_flag = "PASS" if delayed_pass else "FAIL"
    print(f"  [{status_flag}] Delayed Shipments: {summary.delayed_orders_count}/{summary.total_orders} ({delayed_pct:.1f}%)")

    print("\n--- 4. Recency Window (Requirement: 0 to 30 days) ---")
    recency_pass = 0 <= summary.min_days_since_created and summary.max_days_since_created <= 30
    status_flag = "PASS" if recency_pass else "FAIL"
    print(f"  [{status_flag}] Days Since Created: min={summary.min_days_since_created}, max={summary.max_days_since_created}")

    print("\n--- 5. Task 6 Lookup Tool Verification ---")
    sample_order = ORDERS[0]
    sample_lookup = check_order_status(sample_order.record_id)
    print(f"  Sample lookup ({sample_order.record_id}):")
    print(f"    status: {sample_lookup['status']}")
    print(f"    order_value_inr: ₹{sample_lookup['order_value_inr']}")
    print(f"    days_since_created: {sample_lookup['days_since_created']}")
    print(f"    delayed_shipment: {sample_lookup['delayed_shipment']}")
    print(f"    escalation_score: {sample_lookup['escalation_score']}")
    print(f"    escalate_recommended: {sample_lookup['escalate_recommended']}")
    print("=" * 70)


if __name__ == "__main__":
    print_validation_report()
