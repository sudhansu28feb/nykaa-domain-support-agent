"""
Output Guardrails for Nykaa Support Agent (Task 10).

Strictly complies with Capstone Project Brief:
1. Groundedness validation against retrieved context.
2. Refuses to answer when retrieved context does not support the query or contains ungrounded claims.
3. Fallback to calibrated official policy refusal.
"""

import re
from typing import List, Optional
from pydantic import BaseModel, Field

from nykaa_support.rag.generator import FALLBACK_RESPONSE_TEXT

FALLBACK_REFUSAL_TEXT = FALLBACK_RESPONSE_TEXT


class OutputGuardrailResult(BaseModel):
    """Structured result of output guardrail groundedness validation."""
    raw_output: str = Field(description="Original draft response generated by agent")
    final_output: str = Field(description="Validated customer-facing response (unchanged or fallback refusal)")
    is_grounded: bool = Field(description="Whether the response is fully grounded in retrieved context")
    ungrounded_claims: List[str] = Field(default_factory=list, description="Specific ungrounded phrases detected")
    refusal_triggered: bool = Field(default=False, description="Whether guardrail refused answer due to ungroundedness")
    reason: str = Field(description="Explanation of guardrail assessment")


# Specific ungrounded policy claims that violate Nykaa official documentation
KNOWN_UNGROUNDED_PATTERNS = [
    r'\b(?:30|45|60|90)[\s\-]days?\s+(?:return|replacement|refund)\b',  # Nykaa policy is max 15 days
    r'\bfree\s+(?:unlimited\s+)?returns?\s+forever\b',
    r'\b100%\s+guaranteed\s+cash\s+refund\s+for\s+opened\s+beauty\b',   # Opened cosmetics are non-returnable
    r'\bfull\s+refund\s+without\s+returning\s+the\s+item\b',
    r'\bfree\s+international\s+shipping\s+to\s+(?:any|all)\s+countries?\b',
]


def validate_groundedness(
    draft_response: str,
    retrieved_context: Optional[str] = None,
    similarity_score: Optional[float] = None,
    threshold: float = 0.35
) -> OutputGuardrailResult:
    """
    Validate draft response groundedness against retrieved context:
    1. If similarity_score is below calibrated threshold (0.35), refuse to answer.
    2. If retrieved_context is empty or indicates fallback, refuse to answer.
    3. If draft contains explicit ungrounded policy claims not supported by context, refuse to answer.
    """
    # 1. Check similarity threshold
    if similarity_score is not None and similarity_score < threshold:
        return OutputGuardrailResult(
            raw_output=draft_response,
            final_output=FALLBACK_REFUSAL_TEXT,
            is_grounded=False,
            ungrounded_claims=[f"Retrieval similarity {similarity_score:.4f} < threshold {threshold}"],
            refusal_triggered=True,
            reason=f"Refusal triggered: Top similarity score ({similarity_score:.4f}) below calibrated threshold ({threshold})."
        )

    # 2. Check empty or fallback context
    if not retrieved_context or len(retrieved_context.strip()) == 0 or "No relevant policy found" in retrieved_context:
        return OutputGuardrailResult(
            raw_output=draft_response,
            final_output=FALLBACK_REFUSAL_TEXT,
            is_grounded=False,
            ungrounded_claims=["No supporting policy context retrieved"],
            refusal_triggered=True,
            reason="Refusal triggered: Knowledge base returned zero supporting policy context."
        )

    # 3. Check for specific hallucinated or ungrounded claims
    detected_hallucinations = []
    for pattern in KNOWN_UNGROUNDED_PATTERNS:
        match = re.search(pattern, draft_response, re.IGNORECASE)
        if match:
            # Check if this phrase is actually supported in retrieved context
            phrase = match.group(0)
            if phrase.lower() not in retrieved_context.lower():
                detected_hallucinations.append(phrase)

    if detected_hallucinations:
        return OutputGuardrailResult(
            raw_output=draft_response,
            final_output=FALLBACK_REFUSAL_TEXT,
            is_grounded=False,
            ungrounded_claims=detected_hallucinations,
            refusal_triggered=True,
            reason=f"Refusal triggered: Draft response made ungrounded policy claims: {detected_hallucinations}"
        )

    # Output is verified grounded
    return OutputGuardrailResult(
        raw_output=draft_response,
        final_output=draft_response,
        is_grounded=True,
        ungrounded_claims=[],
        refusal_triggered=False,
        reason="Output verified: Response is grounded in retrieved Nykaa policy context."
    )
